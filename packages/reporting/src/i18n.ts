/**
 * Returns localized report copy for the given language. The key is a string
 * (domain tokens such as `iss.<STATUS>` or `metric.<key>` are built
 * dynamically), and unknown keys fall back to the key itself.
 */
export function rt(lang: ReportLanguage, key: string): string {
  const table = lang === 'ar' ? ar : en;
  return table[key as ReportStringKey] ?? key;
}
